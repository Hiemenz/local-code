"""State-file management and zsh script generation for shell integration.

State files live at {data_dir}/active/{sha1} where sha1 is the same 16-char
prefix of sha1(realpath) used by SessionStore — so the shell precmd can find
the matching file without starting Python.
"""

from __future__ import annotations

import hashlib
from pathlib import Path


def _project_sha1(project_root: str) -> str:
    return hashlib.sha1(project_root.encode()).hexdigest()[:16]


def write_active(base_dir: Path, project_root: str, session_id: str) -> None:
    """Record the active session so the shell prompt indicator can read it cheaply."""
    active_dir = base_dir / "active"
    active_dir.mkdir(parents=True, exist_ok=True)
    (active_dir / _project_sha1(project_root)).write_text(session_id, encoding="utf-8")


def clear_active(base_dir: Path, project_root: str) -> None:
    """Remove the state file on process exit."""
    target = base_dir / "active" / _project_sha1(project_root)
    target.unlink(missing_ok=True)


# ---------------------------------------------------------------------------
# zsh integration script
# ---------------------------------------------------------------------------

_ZSH_SCRIPT = r"""# localcode shell integration — generated by `localcode --shell-integration`
#
# Add to ~/.zshrc:
#   command -v localcode &>/dev/null && eval "$(localcode --shell-integration)"
#
# To suppress the automatic RPROMPT change, set LOCALCODE_NO_RPROMPT=1 before
# sourcing and add $_lc_indicator to your theme manually.

_lc_data="${XDG_DATA_HOME:-$HOME/.local/share}/localcode"

# --- precmd hook: refresh $_lc_indicator on every prompt -------------------

_lc_precmd() {
  local _sha1 _sf
  # Replicate Python's hashlib.sha1(realpath.encode()).hexdigest()[:16]
  _sha1=$(printf '%s' "${PWD:A}" | (shasum 2>/dev/null || sha1sum) | awk '{print substr($1,1,16)}')
  _sf="${_lc_data}/active/${_sha1}"
  if [[ -f "$_sf" ]]; then
    _lc_session_id=$(<"$_sf")
    _lc_indicator="%F{cyan}[lc]%f"
  else
    _lc_session_id=""
    _lc_indicator=""
  fi
}

precmd_functions+=(_lc_precmd)

# Add $_lc_indicator to RPROMPT when it is currently unset/empty.
# If you use oh-my-zsh or a theme that manages RPROMPT, set
# LOCALCODE_NO_RPROMPT=1 and reference $_lc_indicator in your theme instead.
if [[ -z "${LOCALCODE_NO_RPROMPT}" && -z "${RPROMPT}" ]]; then
  setopt PROMPT_SUBST
  RPROMPT='$_lc_indicator'
fi

# --- lc(): wrapper function ------------------------------------------------
#
# Differences from calling `localcode` directly:
#   - Auto-continues the most recent session for $PWD (adds --continue unless
#     --resume, --continue, or -p/--print are already present).
#   - Exports LOCALCODE_SHELL_BRANCH with the current git branch so the agent
#     can reference it without running git itself.

lc() {
  local _branch _skip_resume=0 _a
  _branch=$(git -C "$PWD" symbolic-ref --short HEAD 2>/dev/null)

  for _a in "$@"; do
    case "$_a" in
      --resume|--continue|-p|--print) _skip_resume=1; break ;;
    esac
  done

  if (( _skip_resume )); then
    LOCALCODE_SHELL_BRANCH="$_branch" command localcode "$@"
  else
    LOCALCODE_SHELL_BRANCH="$_branch" command localcode --continue "$@"
  fi
}
"""


def zsh_script() -> str:
    return _ZSH_SCRIPT
